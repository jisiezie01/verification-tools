import { catalogFixture } from "./catalog-browser-fixture.mjs"
import assert from "node:assert/strict"
import { makeCatalog } from "./fixtures/tools.mjs"
import { connectBrowser } from "./browser-client.mjs"

const browser = await connectBrowser()
const { send, evaluate, waitFor, settle, navigate, click, clickText, fill, drag, screenshot } = browser
const origin = "http://127.0.0.1:5173"
const boardSelector = '[data-category-board="references"]'
const agreementScope = 'document.querySelector(\'[data-board-tool="agreement"]\')'
const readCategory = () => evaluate("(await (await fetch('/__catalog')).json()).categories.find(category => category.id === 'references')")
const openGuard = () => waitFor("!!document.querySelector('dialog[open]')")

const catalogFile = await catalogFixture()

try {
    await send("Emulation.setDeviceMetricsOverride", { width: 1536, height: 1100, deviceScaleFactor: 1, mobile: false })
    await navigate(`${origin}/manage-tools?category=references`)
    const fixture = makeCatalog()
    await catalogFile.seed(fixture)
    await navigate()
    await waitFor("document.querySelectorAll('[data-board-tool]').length === 2")
    assert.equal(await evaluate("document.querySelectorAll('[aria-label=\"Tool categories\"] button').length"), 2)
    assert.equal(await evaluate(`getComputedStyle(document.querySelector('${boardSelector}')).flexWrap`), "wrap")
    assert.equal(await evaluate(`getComputedStyle(document.querySelector('${boardSelector}')).flexDirection`), "row")
    assert.equal(await evaluate("document.querySelectorAll('[data-library-tool]').length"), 1)
    assert.equal(await evaluate("!!document.querySelector('[data-board-tool=\"agreement\"] [data-runtime-element=\"agreement-output\"]')"), false)
    await evaluate("window.copiedValues = []; Object.defineProperty(navigator, 'clipboard', {configurable:true,value:{writeText:async value => {window.copiedValues.push(value)}}})")

    await fill("Full name", "jane doe")
    await fill("Email", "wrong@")
    await clickText("Generate", agreementScope)
    assert.equal(await evaluate("!!document.querySelector('[data-runtime-element=\"agreement-output\"]')"), false)
    assert.ok((await evaluate("document.querySelector('[data-board-tool=\"agreement\"]').textContent")).includes("valid email"))
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-email\"] input').getAttribute('aria-invalid')"), "true")
    await fill("Email", "jane@example.com")
    await fill("Contact number", "1234567890999")
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-phone\"] input').value"), "(123) 456-7890")
    await click('[data-runtime-element="agreement-consent"] input[value="yes"]')
    await clickText("Generate", agreementScope)
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-output\"]').textContent"), "I, Jane Doe agree")
    assert.equal(await evaluate("(() => {const card=document.querySelector('[data-board-tool=\"agreement\"]');return card.scrollHeight <= card.clientHeight+2})()"), true, "Generated output must grow the card without clipping")
    await clickText("Copy result", agreementScope)
    await waitFor("window.copiedValues.length === 1")
    assert.equal(await evaluate("window.copiedValues[0]"), "I, Jane Doe agree")
    assert.ok(browser.dialogs.some(dialog => dialog.type === "alert" && dialog.message === "Result copied."))
    await click('[aria-label="Copy Full name"]')
    assert.equal(await evaluate("window.copiedValues.at(-1)"), "Jane Doe")
    assert.equal(await evaluate("document.querySelector('[aria-label=\"Category configuration\"] [role=status]').textContent"), "Your board is ready.")
    await clickText("Reset", agreementScope)
    assert.equal(await evaluate("Array.from(document.querySelectorAll('[data-board-tool=\"agreement\"] input')).every(input => input.type === 'radio' ? !input.checked : !input.value)"), true)
    assert.equal(await evaluate("!!document.querySelector('[data-runtime-element=\"agreement-output\"]')"), false)
    await click('[data-runtime-element="agreement-consent"] input[value="no"]')
    await fill("Age", "30")
    await fill("Full name", "sam")
    await clickText("Generate", agreementScope)
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-output\"]').textContent"), "Adult: Sam")
    await clickText("Reset", agreementScope)
    await click('[data-runtime-element="agreement-consent"] input[value="no"]')
    await fill("Age", "0")
    await fill("Reference date", "2000-01-01")
    await clickText("Generate", agreementScope)
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-output\"]').textContent"), "Earlier date: 2000-01-01")
    await clickText("Reset", agreementScope)
    await clickText("Today", agreementScope)
    assert.match(await evaluate("document.querySelector('[data-runtime-element=\"agreement-date\"] input').value"), /^\d{4}-\d{2}-\d{2}$/)
    await clickText("Reset", agreementScope)
    await screenshot("manage-tools-desktop")

    await click('[aria-label="Remove Phone formatter from board"]')
    assert.equal(await evaluate("!!document.querySelector('[data-library-tool=\"phone\"]')"), true)
    await clickText("Formatters", 'document.querySelector(\'[aria-label="Tool categories"]\')')
    await openGuard()
    await clickText("Stay", "document.querySelector('dialog')")
    assert.ok((await evaluate("location.search")).includes("references"))
    assert.equal(await evaluate("!!document.querySelector('[data-library-tool=\"phone\"]')"), true)
    await fill("Category name", "References updated")
    await clickText("Formatters", 'document.querySelector(\'[aria-label="Tool categories"]\')')
    await openGuard()
    await clickText("Save and continue", "document.querySelector('dialog')")
    await waitFor("location.search.includes('formatters')")
    let category = await readCategory()
    assert.equal(category.name, "References updated")
    assert.ok(category.board.removedToolIds.includes("phone"))
    await clickText("References updated", 'document.querySelector(\'[aria-label="Tool categories"]\')')
    await waitFor("!!document.querySelector('[data-library-tool=\"phone\"]')")
    await drag('[aria-label="Drag Phone formatter to board"]', boardSelector)
    assert.equal(await evaluate("!!document.querySelector('[data-board-tool=\"phone\"]')"), true)
    assert.equal(await evaluate("!!document.querySelector('[data-library-tool=\"phone\"]')"), false)
    await drag('[aria-label="Move Phone formatter"]', '[data-board-tool="agreement"]')
    assert.equal(await evaluate("document.querySelector('[data-board-tool]').dataset.boardTool"), "phone")
    await drag('[aria-label="Drag Archived helper to board"]', boardSelector)
    assert.equal(await evaluate("!!document.querySelector('[data-board-tool=\"archived\"]')"), true)
    assert.equal(await evaluate("!!document.querySelector('[data-library-tool=\"archived\"]')"), false)
    await clickText("Save changes")
    assert.equal(await evaluate("(await (await fetch('/__catalog')).json()).tools.find(tool => tool.id === 'archived').archived"), false)

    await fill("Flex direction", "column")
    await settle()
    assert.equal(await evaluate("(() => {const cards=[...document.querySelectorAll('[data-board-tool]')];return cards.some(card => card.getBoundingClientRect().x > cards[0].getBoundingClientRect().x+100)})()"), true, "Column wrapping should use the available board height")
    await fill("Flex wrapping", "nowrap")
    await fill("Spacing (px)", "28")
    await clickText("Save changes")
    category = await readCategory()
    assert.equal(category.board.direction, "column")
    assert.equal(category.board.wrap, "nowrap")
    assert.equal(category.board.gap, 28)
    await fill("Flex direction", "row")
    await fill("Flex wrapping", "wrap")
    await clickText("Save changes")

    const resize = await evaluate("(() => {const button=document.querySelector('[data-board-tool=\"phone\"] [aria-label=\"Resize tool\"]');button.scrollIntoView({block:'center'});const rect=button.getBoundingClientRect();return {x:rect.x+rect.width/2,y:rect.y+rect.height/2}})()")
    await send("Input.dispatchMouseEvent", { type: "mouseMoved", ...resize })
    await send("Input.dispatchMouseEvent", { type: "mousePressed", ...resize, button: "left", clickCount: 1 })
    await send("Input.dispatchMouseEvent", { type: "mouseMoved", x: resize.x - 800, y: resize.y - 800, button: "left", buttons: 1 })
    await send("Input.dispatchMouseEvent", { type: "mouseReleased", x: resize.x - 800, y: resize.y - 800, button: "left", clickCount: 1 })
    await settle()
    assert.equal(await evaluate("(() => {const card=document.querySelector('[data-board-tool=\"phone\"]');return card.getBoundingClientRect().width >= Number(card.dataset.minWidth) && card.getBoundingClientRect().height >= Number(card.dataset.minHeight) && card.scrollHeight <= card.clientHeight+2})()"), true)
    await clickText("Save changes")
    await navigate()
    assert.equal(await evaluate("document.querySelector('[data-board-tool]').dataset.boardTool"), "phone")
    assert.equal(await evaluate("document.querySelectorAll('[data-board-tool]').length"), 3)

    await fill("Category name", "Keep this unsaved name")
    await evaluate("window.originalFetch = window.fetch; window.fetch = async function(url,options) {if(options?.method === 'PUT') throw new Error('Test save failure'); return window.originalFetch(url,options)}")
    await clickText("Create new tool")
    await openGuard()
    await clickText("Save and continue", "document.querySelector('dialog')")
    assert.equal(await evaluate("location.pathname"), "/manage-tools")
    assert.ok((await evaluate("document.querySelector('dialog').textContent")).includes("could not be saved"))
    await evaluate("window.fetch = window.originalFetch")
    await clickText("Stay", "document.querySelector('dialog')")
    await fill("Category name", "References updated")

    await fill("Category name", "Temporary name")
    await clickText("Create new tool")
    await openGuard()
    await clickText("Discard changes", "document.querySelector('dialog')")
    await waitFor("location.pathname === '/create-tool'")
    assert.equal(await evaluate("Array.from(document.querySelectorAll('select option:checked')).some(option => option.value === 'references')"), true)
    assert.equal((await readCategory()).name, "References updated")
    await clickText("Manage tools")
    await waitFor("location.pathname === '/manage-tools'")
    await click('[aria-label="Remove Phone formatter from board"]')
    await clickText("Save changes")
    await clickText("View", 'document.querySelector(\'[data-library-tool="phone"]\')')
    await waitFor("location.pathname === '/tools/phone'")
    assert.ok((await evaluate("document.body.textContent")).includes("Phone to format"))
    await clickText("Edit tool")
    await waitFor("location.pathname === '/create-tool'")
    await fill("Tool name", "Phone formatter edited")
    await clickText("Save tool")
    await clickText("Manage tools")
    await waitFor("!!document.querySelector('[data-library-tool=\"phone\"]')")
    assert.ok((await evaluate("document.querySelector('[data-library-tool=\"phone\"]').textContent")).includes("Phone formatter edited"))

    assert.equal(await evaluate("!!document.querySelector('[data-board-tool=\"agreement\"] [title=\"Archive tool\"]')"), false)
    await click('[aria-label="Remove Agreement generator from board"]')
    await click('[aria-label="Archive Agreement generator"]')
    await clickText("Archive category")
    await clickText("Save changes")
    assert.equal((await readCategory()).archived, true)
    assert.equal(await evaluate("(await (await fetch('/__catalog')).json()).tools.find(tool => tool.id === 'agreement').archived"), true)
    assert.equal(await evaluate("!!document.querySelector('[aria-label=\"Archived tools off board\"] [data-library-tool=\"agreement\"]')"), true)
    await clickText("Restore category")
    await clickText("Save changes")
    await fill("Category name", "Unsaved reload test")
    assert.equal(await evaluate("(() => {const event = new Event('beforeunload',{cancelable:true});window.dispatchEvent(event);return event.defaultPrevented})()"), true)
    browser.setUnloadDecision(false)
    const dialogCount = browser.dialogs.length
    await send("Page.reload")
    await settle()
    assert.ok(browser.dialogs.length > dialogCount && browser.dialogs.at(-1).type === "beforeunload")
    assert.ok((await evaluate("document.querySelector('[aria-label=\"Category configuration\"]').textContent")).includes("Unsaved changes"))
    await clickText("Save changes")
    browser.setUnloadDecision(true)
    await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: false })
    await settle()
    assert.equal(await evaluate("document.documentElement.scrollWidth > innerWidth"), false)
    await screenshot("manage-tools-mobile")
    assert.deepEqual(browser.runtimeErrors, [])
    console.log("Manage-tools browser checks passed: renderer behavior, board defaults, drag/drop/order, archive/restore, minimum resize, persistence, View/Edit/Create, Save/Discard/Stay, native beforeunload, and responsive layout.")
} finally { browser.close(); await catalogFile.restore() }
