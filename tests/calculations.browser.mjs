import assert from "node:assert/strict"
import { connectBrowser } from "./browser-client.mjs"
import { pagesPrefix, startPagesServer } from "./static-pages-server.mjs"
import { makeCalculationCatalog } from "./fixtures/calculations.mjs"

const server = await startPagesServer(4176, makeCalculationCatalog())
const browser = await connectBrowser()
const { navigate, waitFor, click, clickText, fill, evaluate } = browser
const result = () => evaluate("document.querySelector('[data-runtime-element=\"result\"]')?.textContent ?? ''")
const fieldValue = label => evaluate(`(() => { const label = Array.from(document.querySelectorAll('label')).find(item => item.textContent === ${JSON.stringify(label)}); return document.getElementById(label.htmlFor).value; })()`)
const saveAndUse = async () => {
    await clickText("Save tool")
    await waitFor("document.body.textContent.includes('Applied to this demo only')")
    await clickText("Manage tools")
    await clickText("Use tools")
    await waitFor("!!document.querySelector('[data-tools-board]')")
}

try {
    await browser.send("Network.enable")
    await browser.send("Network.setBlockedURLs", { urls: ["*googletagmanager.com/*", "*google-analytics.com/*", "*analytics.google.com/*", "*doubleclick.net/*"] })
    await browser.send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
    await navigate(`http://127.0.0.1:4176${pagesPrefix}create-tool/?toolId=calculator`)
    await click('[data-builder-element="result"]')
    await clickText("Add condition")
    await fill("Condition source", "calculation")
    await fill("Number 1", "a")
    await fill("Number 2", "b")
    await clickText("Add number input")
    await fill("Number 3", "c")
    await click('[aria-label="Move number 3 earlier"]')
    assert.equal(await fieldValue("Number 2"), "c")
    await click('[aria-label="Move number 2 later"]')
    assert.equal(await fieldValue("Number 3"), "c")
    await clickText("Add number input")
    await click('[aria-label="Remove number 4"]')
    await fill("Comparison", "at-least")
    await fill("Comparison number", "100")
    await fill("Use this text when matched", "Meets target: ")
    await clickText("${calc.result}")
    await fill("Use this text when matched", "Meets target: ${calc.result}. Monthly: ${Currency(((amount_a * amount_b) * 52) / 12)}. JPY: ${Currency(((amount_a * amount_b) * 52) / 12, 'JPY')}.")
    assert.ok(await evaluate("document.body.textContent.includes('((amount_a + amount_b) + amount_c)')"))
    await browser.screenshot("calculation-editor")
    await saveAndUse()
    await clickText("Generate")
    assert.equal(await result(), "")
    assert.ok(await evaluate("document.body.textContent.includes('Please enter Amount A') && document.body.textContent.includes('Please enter Amount B') && document.body.textContent.includes('Please enter Amount C')"))
    await fill("Amount A", "60")
    await fill("Amount B", "30")
    await fill("Amount C", "20")
    await clickText("Generate")
    assert.equal(await result(), "Meets target: 110. Monthly: $7,800.00. JPY: ￥7,800.00.")
    await fill("Amount A", "1")
    await clickText("Generate")
    assert.equal(await result(), "Below target.")

    for (const [operation, expected] of [["difference", 13], ["product", 200], ["quotient", 2]]) {
        await clickText("Manage tools")
        await click('[aria-label="Edit Calculation example"]')
        await click('[data-builder-element="result"]')
        assert.equal(await fieldValue("Condition source"), "calculation", "The saved rule must reopen as a calculation")
        assert.equal(await fieldValue("Number 3"), "c")
        await fill("Operation", operation)
        await fill("Comparison", "equals")
        await fill("Comparison number", String(expected))
        await saveAndUse()
        await fill("Amount A", "20")
        await fill("Amount B", "5")
        await fill("Amount C", "2")
        await clickText("Generate")
        assert.equal(await result(), `Meets target: ${expected}. Monthly: $433.33. JPY: ￥433.33.`, operation)
    }
    await evaluate("Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.copiedResult = value } } })")
    await clickText("Copy")
    assert.equal(await evaluate("window.copiedResult"), "Meets target: 2. Monthly: $433.33. JPY: ￥433.33.")
    await fill("Amount C", "0")
    await clickText("Generate")
    assert.ok(await evaluate("document.body.textContent.includes('Cannot divide by zero')"))
    assert.equal(await result(), "Meets target: 2. Monthly: $433.33. JPY: ￥433.33.", "A failed calculation preserves the last result")
    await clickText("Reset")
    assert.equal(await result(), "")

    await clickText("Manage tools")
    await click('[aria-label="Edit Calculation example"]')
    await click('[data-builder-element="result"]')
    await fill("Compare against", "variable")
    await fill("Comparison number", "target")
    await fill("Offset", "1")
    await saveAndUse()
    await fill("Amount A", "20")
    await fill("Amount B", "5")
    await fill("Amount C", "2")
    await fill("Target amount", "1")
    await clickText("Generate")
    assert.equal(await result(), "Meets target: 2. Monthly: $433.33. JPY: ￥433.33.")
    await clickText("Manage tools")
    await click('[aria-label="Edit Calculation example"]')
    await click('[data-builder-element="a"]')
    await fill("Default value", "7")
    await saveAndUse()
    assert.equal(await fieldValue("Amount A"), "7")
    await clickText("Reset")
    assert.equal(await fieldValue("Amount A"), "7", "Reset restores the configured default")
    assert.deepEqual(browser.runtimeErrors, [])
    console.log("Calculation browser checks passed: authoring, ordered operands, adding/removing/reordering, save/reopen, all four operations, formulas, currency formatting, fallback, required fields, division by zero, copy/reset, default values, and variable comparisons with offsets.")
} finally {
    await browser.send("Page.navigate", { url: "about:blank" })
    await browser.send("Network.setBlockedURLs", { urls: [] })
    browser.close()
    server.closeAllConnections()
    await new Promise(resolve => server.close(resolve))
}
