import assert from "node:assert/strict"
import { startPagesServer, pagesPrefix } from "./static-pages-server.mjs"
import { connectBrowser } from "./browser-client.mjs"
import { makeCatalog } from "./fixtures/tools.mjs"

const fixture = makeCatalog()
fixture.categories[0].board = { direction: "column", wrap: "nowrap", gap: 31, placements: [{ toolId: "phone", width: 580 }], removedToolIds: ["agreement"] }
const prefix = pagesPrefix
const server = await startPagesServer(4175, fixture)
const browser = await connectBrowser()
try {
    await browser.send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
    await browser.send("Page.navigate", { url: "about:blank" })
    await browser.waitFor("location.href === 'about:blank'")
    await browser.navigate(`http://127.0.0.1:4175${prefix}#/tools?category=references`)
    await browser.waitFor("!!document.querySelector('[data-tools-board]')")
    assert.equal(await browser.evaluate("document.querySelectorAll('[data-published-tool]').length"), 1)
    assert.equal(await browser.evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).gap"), "31px")
    assert.equal(await browser.evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).flexDirection"), "column")
    await browser.evaluate("localStorage.setItem('verification-tools.tools.v1', 'broken'); localStorage.setItem('verification-tools.categories.v1','[]')")
    await browser.navigate()
    assert.equal(await browser.evaluate("document.querySelector('[data-published-tool]').dataset.publishedTool"), "phone")
    assert.ok(await browser.evaluate("!!document.querySelector('[data-demo-notice]')"))
    await browser.evaluate("window.demoWrites = []; const originalFetch = window.fetch; window.fetch = (...args) => { const method = args[1]?.method ?? args[0]?.method ?? 'GET'; if (method !== 'GET') window.demoWrites.push(method); return originalFetch(...args); }")
    await browser.clickText("Manage tools")
    await browser.fill("Category name", "Demo references")
    await browser.fill("Spacing (px)", 47)
    await browser.clickText("Save changes")
    await browser.waitFor("document.body.textContent.includes('Applied to this demo only')")
    await browser.clickText("Use tools")
    assert.equal(await browser.evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).gap"), "47px")
    assert.ok(await browser.evaluate("document.body.textContent.includes('Demo references')"))
    await browser.clickText("Manage tools")
    await browser.click('[aria-label="Edit Phone formatter"]')
    await browser.fill("Tool name", "Edited phone formatter")
    await browser.clickText("Save tool")
    await browser.waitFor("document.body.textContent.includes('Applied to this demo only')")
    await browser.clickText("Manage tools")
    assert.ok(await browser.evaluate("document.body.textContent.includes('Edited phone formatter')"))
    await browser.clickText("Create new tool")
    await browser.fill("Tool name", "Visitor demo tool")
    await browser.clickText("Create category")
    await browser.fill("Category name", "Visitor category")
    await browser.clickText("Create category", "document.querySelector('dialog')")
    await browser.waitFor("!document.querySelector('dialog')")
    await browser.click('[aria-label="Add text input"]')
    await browser.clickText("Save tool")
    await browser.waitFor("document.body.textContent.includes('Applied to this demo only')")
    await browser.clickText("Manage tools")
    await browser.waitFor("!!document.querySelector('[data-board-tool]')")
    assert.ok(await browser.evaluate("document.body.textContent.includes('Visitor demo tool')"))
    await browser.clickText("Use tools")
    assert.equal(await browser.evaluate("document.querySelectorAll('[data-published-tool]').length"), 1)
    assert.ok(await browser.evaluate("!!document.querySelector('[data-published-tool] input')"))
    await browser.fill("Text input", "Try it out")
    assert.equal(await browser.evaluate("document.querySelector('[data-published-tool] input').value"), "Try it out")
    assert.deepEqual(await browser.evaluate("window.demoWrites"), [], "Demo saves must not send HTTP writes")
    await browser.navigate()
    assert.ok(await browser.evaluate("!document.body.textContent.includes('Visitor category') && !document.body.textContent.includes('Visitor demo tool')"))
    assert.ok(await browser.evaluate("document.body.textContent.includes('Reference tools')"))
    assert.equal(await browser.evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).gap"), "31px")
    await browser.navigate(`http://127.0.0.1:4175${prefix}create-tool/`)
    assert.ok(await browser.evaluate("!!document.querySelector('[aria-label=\"Tool selection\"]')"))
    await browser.navigate(`http://127.0.0.1:4175${prefix}manage-tools/`)
    assert.ok(await browser.evaluate("!!document.querySelector('[aria-label=\"Category configuration\"]')"))
    assert.deepEqual(browser.runtimeErrors, [])
    console.log("Published browser checks passed: nested Pages path, shared JSON layout, temporary layout edits, tool/category creation, runtime use, refresh reset, no remote writes, and direct editor routes.")
} finally {
    browser.close()
    await new Promise(resolve => server.close(resolve))
}
