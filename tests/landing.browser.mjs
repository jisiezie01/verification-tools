import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { connectBrowser } from "./browser-client.mjs"
import { pagesPrefix, startPagesServer } from "./static-pages-server.mjs"

const server = await startPagesServer(4176)
const browser = await connectBrowser()
const origin = `http://127.0.0.1:4176${pagesPrefix}`
try {
    const source = await (await fetch(origin)).text()
    assert.ok(source.includes('id="hero-title"') && source.includes("Verification work."), "Crawlable page content must exist before JavaScript")
    assert.ok(!source.includes('id="root"'), "Landing page must not depend on the React application")
    assert.ok(!source.includes("%BASE_URL%"))
    await browser.send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
    await browser.navigate(origin)
    assert.equal(await browser.evaluate("document.querySelectorAll('h1').length"), 1)
    assert.equal(await browser.evaluate("document.querySelector('link[rel=canonical]').href"), "https://jisiezie01.github.io/verification-tools/")
    assert.equal(await browser.evaluate("JSON.parse(document.querySelector('script[type=\"application/ld+json\"]').textContent)['@graph'].length"), 2)
    // Load deferred screenshots before inspecting them and capturing the page.
    await browser.evaluate("document.querySelectorAll('img').forEach(img => img.loading = 'eager')")
    await browser.waitFor("Array.from(document.images).every(image => image.complete && image.naturalWidth > 0)")
    assert.equal(await browser.evaluate("document.documentElement.scrollWidth <= innerWidth"), true)
    await browser.screenshot("landing-desktop")
    await browser.click(".faq-list details:nth-child(2) summary")
    assert.equal(await browser.evaluate("document.querySelector('.faq-list details:nth-child(2)').open"), true)
    await browser.send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
    await browser.settle()
    assert.equal(await browser.evaluate("document.documentElement.scrollWidth <= innerWidth"), true)
    await browser.screenshot("landing-mobile")
    await browser.send("Emulation.setDeviceMetricsOverride", { width: 320, height: 700, deviceScaleFactor: 1, mobile: true })
    await browser.settle()
    assert.equal(await browser.evaluate("document.documentElement.scrollWidth <= innerWidth"), true, "No overflow on narrow phones")
    await browser.send("Emulation.setScriptExecutionDisabled", { value: true })
    await browser.send("Page.navigate", { url: origin })
    await browser.waitFor("document.readyState === 'complete' && !!document.querySelector('h1')")
    assert.ok(await browser.evaluate("document.querySelector('h1').textContent.includes('Verification work')"))
    await browser.evaluate("document.querySelector('.faq-list details:nth-child(3) summary').click()")
    assert.equal(await browser.evaluate("document.querySelector('.faq-list details:nth-child(3)').open"), true)
    await browser.send("Emulation.setScriptExecutionDisabled", { value: false })
    await browser.send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
    await browser.navigate(origin)
    await browser.click(".hero-actions .button")
    await browser.waitFor("!!document.querySelector('[data-tools-board]')")
    assert.equal(await browser.evaluate("location.pathname"), pagesPrefix + "tools/")
    await browser.navigate()
    assert.ok(await browser.evaluate("!!document.querySelector('[data-tools-board]')"))
    const catalog = JSON.parse(await readFile("dist/tool-catalog.json", "utf8"))
    const tool = catalog.tools.find(tool => !tool.archived)
    await browser.navigate(origin + `tools/${encodeURIComponent(tool.id)}/`)
    assert.equal(await browser.evaluate("document.querySelector('h1').textContent"), tool.name)
    await browser.navigate()
    assert.equal(await browser.evaluate("document.querySelector('h1').textContent"), tool.name)
    await browser.navigate(origin + "#/tools")
    await browser.waitFor("location.pathname.startsWith('/verification-tools/tools') && !!document.querySelector('[data-tools-board]')")
    await browser.navigate(origin + "create-tool/")
    await browser.waitFor("location.pathname === '/verification-tools/tools'")
    assert.equal((await fetch(origin + "missing-page/")).status, 404)
    assert.ok((await (await fetch(origin + "sitemap.xml")).text()).includes("https://jisiezie01.github.io/verification-tools/"))
    assert.deepEqual(browser.runtimeErrors, [])
    console.log("Landing checks passed: static SEO content, all screenshots, FAQ, desktop/390px/320px layouts, no-JavaScript content, workspace navigation, direct links, reload, legacy redirects, and sitemap.")
} finally {
    await browser.send("Emulation.setScriptExecutionDisabled", { value: false })
    browser.close()
    await new Promise(resolve => server.close(resolve))
}
