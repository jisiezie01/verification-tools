import { catalogFixture } from "./catalog-browser-fixture.mjs"
import assert from "node:assert/strict"
import { makeCatalog } from "./fixtures/tools.mjs"
import { importTypeScript } from "./import-typescript.mjs"
import { connectBrowser } from "./browser-client.mjs"

const { createElement } = await importTypeScript("src/screens/CreateTool/functions.ts")
const { sharedInputId } = await importTypeScript("src/data/toolVariables/functions.ts")
const browser = await connectBrowser()
const { send, evaluate, navigate, waitFor, click, clickText, fill, screenshot, settle } = browser
const origin = "http://127.0.0.1:5173"
const consumerScope = 'document.querySelector(\'[data-tool-content="consumer"]\')'
const sourceScope = 'document.querySelector(\'[data-tool-content="agreement"]\')'
const readConsumerOutput = () => evaluate('document.querySelector(\'[data-runtime-element="consumer-output"]\')?.textContent')

const catalogFile = await catalogFixture()

try {
    await send("Emulation.setDeviceMetricsOverride", { width: 1536, height: 1100, deviceScaleFactor: 1, mobile: false })
    await navigate(`${origin}/tools`)
    const catalog = makeCatalog()
    const consumer = { id: "consumer", name: "Shared reference", categoryId: "references", elements: [] }
    consumer.elements.push({ ...createElement("Text input", consumer), id: "consumer-name", variableName: "name_input", label: "Local name" })
    consumer.elements.push({ ...createElement("Output text", consumer), id: "consumer-output", generatedText: { default: "Hello ${global.name_input}, from ${name_input}. Email: ${global.email_input}." }, conditions: [
        { id: "consent", inputId: sharedInputId("agreement", "agreement-consent"), operator: "equals", value: "yes", text: "I, ${global.name_input}, agree (${name_input})." },
        { id: "adult", inputId: sharedInputId("agreement", "agreement-age"), operator: "at-least", value: "18", text: "Adult: ${global.name_input}" },
        { id: "date", inputId: sharedInputId("agreement", "agreement-date"), operator: "less-than", value: "today", text: "Dated: ${global.reference_date}" },
    ] })
    consumer.elements.push({ ...createElement("Generate button", consumer), id: "consumer-generate", link: "consumer-output" }, { ...createElement("Reset button", consumer), id: "consumer-reset" })
    catalog.tools.push(consumer)
    catalog.categories.push({ id: "hidden", name: "Hidden category", archived: true })
    catalog.categories[0].board = { direction: "row", wrap: "wrap", gap: 26, placements: [{ toolId: "consumer", width: 480, height: 450 }, { toolId: "agreement", width: 420, height: 820 }], removedToolIds: ["phone"] }
    await catalogFile.seed(catalog)

    await navigate(`${origin}/create-tool?toolId=agreement`)
    await waitFor("document.querySelector('[aria-label=\"Element selection\"]')?.textContent.includes('Global tool')")
    await evaluate("Array.from(document.querySelectorAll('label')).find(label => label.textContent.trim() === 'Global tool').querySelector('input').click()")
    await click('[data-builder-element="agreement-actions"]')
    await fill("Justify content", "space-between")
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-builder-drop=\"agreement-actions\"]')).justifyContent"), "space-between")
    await clickText("Save tool")
    assert.equal(await evaluate("(await (await fetch('/__catalog')).json()).tools.find(tool => tool.id === 'agreement').isGlobal"), true)
    assert.equal(await evaluate("(await (await fetch('/__catalog')).json()).tools.find(tool => tool.id === 'agreement').elements.find(element => element.id === 'agreement-actions').justifyContent"), "space-between")

    await navigate(`${origin}/create-tool?toolId=consumer`)
    await click('[data-builder-element="consumer-output"]')
    assert.equal(await evaluate("Array.from(document.querySelectorAll('button')).some(button => button.textContent === '${global.name_input}')"), true)
    assert.equal(await evaluate("Array.from(document.querySelectorAll('option')).some(option => option.textContent.includes('global.consent'))"), true)
    await fill("Default generated text", "")
    await clickText("${global.name_input}")
    assert.equal(await evaluate("document.querySelector('textarea').value"), "${global.name_input}")
    await fill("Default generated text", consumer.elements.find(element => element.id === "consumer-output").generatedText.default)
    await clickText("Save tool")
    assert.equal(await evaluate("document.querySelector('[role=alert]')?.textContent ?? ''"), "")

    await navigate(`${origin}/tools?category=references`)
    await waitFor("document.querySelectorAll('[data-published-tool]').length === 2")
    assert.deepEqual(await evaluate("Array.from(document.querySelectorAll('[data-published-tool]')).map(node => node.dataset.publishedTool)"), ["consumer", "agreement"])
    assert.equal(await evaluate("document.querySelectorAll('[aria-label=\"Tool categories\"] button').length"), 2)
    assert.equal(await evaluate("!!document.querySelector('[data-published-tool=\"phone\"], [data-published-tool=\"archived\"], [aria-label^=\"Remove\"], [aria-label^=\"Resize\"]')"), false)
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).gap"), "26px")
    assert.equal(await evaluate("Math.round(document.querySelector('[data-published-tool=\"consumer\"]').getBoundingClientRect().width)"), 480)
    assert.equal(await evaluate("Math.round(document.querySelector('[data-published-tool=\"consumer\"]').getBoundingClientRect().height)"), 450)
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-runtime-element=\"agreement-actions\"] > div')).justifyContent"), "space-between")
    const separation = await evaluate("(() => { const row = document.querySelector('[data-runtime-element=\"agreement-actions\"] > div'); const children = Array.from(row.children); return children.at(-1).getBoundingClientRect().right - children[0].getBoundingClientRect().left })()")
    assert.ok(separation > 350, "space-between stretches the visible action buttons across the container")

    await fill("Full name", "jane doe")
    await fill("Local name", "team")
    await fill("Email", "jane@example.com")
    await click('[data-runtime-element="agreement-consent"] input[value="yes"]')
    await clickText("Generate", consumerScope)
    assert.equal(await readConsumerOutput(), "I, Jane Doe, agree (Team).")
    await fill("Full name", "alex")
    assert.equal(await readConsumerOutput(), "I, Jane Doe, agree (Team).", "outputs remain snapshots until Generate is clicked")
    await clickText("Generate", consumerScope)
    assert.equal(await readConsumerOutput(), "I, Alex, agree (Team).")
    await fill("Email", "invalid")
    await clickText("Generate", consumerScope)
    assert.match(await evaluate(`${consumerScope}.querySelector('[role=alert]').textContent`), /Agreement generator.*valid email/)
    await fill("Email", "alex@example.com")
    await click('[data-runtime-element="agreement-consent"] input[value="no"]')
    await fill("Age", "28")
    await clickText("Generate", consumerScope)
    assert.equal(await readConsumerOutput(), "Adult: Alex")
    await fill("Age", "12")
    await fill("Reference date", "2000-01-01")
    await clickText("Generate", consumerScope)
    assert.equal(await readConsumerOutput(), "Dated: 2000-01-01")
    await clickText("Reset", consumerScope)
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-name\"] input').value"), "alex")
    await fill("Local name", "team")
    await clickText("Reset", sourceScope)
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"consumer-name\"] input').value"), "team")
    await clickText("Generate", consumerScope)
    assert.match(await evaluate(`${consumerScope}.querySelector('[role=alert]').textContent`), /Please select an option/)
    assert.equal(await evaluate(`${consumerScope}.querySelector('[data-runtime-element="consumer-output"]') === null`), true)
    await fill("Full name", "jane doe")
    await fill("Email", "jane@example.com")
    await click('[data-runtime-element="agreement-consent"] input[value="yes"]')
    await clickText("Generate", consumerScope)
    await screenshot("tools-desktop")
    assert.equal(await evaluate("(await (await fetch('/__catalog')).json()).tools.some(tool => 'values' in tool)"), false)

    await clickText("Formatters")
    assert.equal(await evaluate("document.querySelectorAll('[data-published-tool]').length"), 1)
    assert.equal(await evaluate("document.querySelector('[data-published-tool]').dataset.publishedTool"), "dates")
    await clickText("Reference tools")
    assert.equal(await evaluate("document.querySelector('[data-runtime-element=\"agreement-name\"] input').value"), "")
    await clickText("Manage tools")
    await waitFor("!!document.querySelector('[data-category-board]')")
    await fill("Full name", "manage")
    await fill("Local name", "team")
    await click('[data-runtime-element="agreement-consent"] input[value="yes"]')
    await clickText("Generate", consumerScope)
    assert.equal(await readConsumerOutput(), "I, Manage, agree (Team).", "Global inputs also work on the management board")
    await fill("Flex direction", "row-reverse")
    await fill("Flex wrapping", "nowrap")
    await clickText("Save changes")
    await clickText("Use tools")
    await waitFor("!!document.querySelector('[data-tools-board]')")
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).flexDirection"), "row-reverse")
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).flexWrap"), "nowrap")
    await navigate()
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).flexDirection"), "row-reverse")

    await clickText("Manage tools")
    await click('[aria-label="Remove Agreement generator from board"]')
    await clickText("Save changes")
    await clickText("Use tools")
    await clickText("Generate", consumerScope)
    assert.match(await evaluate(`${consumerScope}.querySelector('[role=alert]').textContent`), /shared variable is unavailable/)
    await clickText("Manage tools")
    await clickText("Add to board", 'document.querySelector(\'[data-library-tool="agreement"]\')')
    await fill("Flex direction", "column")
    await fill("Flex wrapping", "wrap")
    await clickText("Save changes")
    await clickText("Use tools")
    await settle()
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).flexDirection"), "column")
    assert.equal(await evaluate("getComputedStyle(document.querySelector('[data-tools-board]')).flexWrap"), "wrap")
    assert.ok(await evaluate("(() => { const cards = Array.from(document.querySelectorAll('[data-published-tool]')); return cards[1].getBoundingClientRect().left > cards[0].getBoundingClientRect().left })()"), "column layouts wrap into another column")

    await send("Emulation.setDeviceMetricsOverride", { width: 375, height: 900, deviceScaleFactor: 1, mobile: true })
    await settle()
    assert.ok(await evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), "wide saved tools scroll inside the board on mobile")
    await screenshot("tools-mobile")
    await catalogFile.seed({ categories: [], tools: [] })
    await navigate()
    await waitFor("document.body.textContent.includes('Your tools start here')")
    await catalogFile.corrupt()
    await navigate()
    await waitFor("document.body.textContent.includes('Tools could not be loaded')")
    assert.deepEqual(browser.runtimeErrors, [])
    console.log("Tools browser checks passed: saved layouts, archives/removals, Global editor settings and picker, shared templates/conditions, reset isolation, missing sources, management preview, space-between, responsive layout, and empty/error states.")
} finally { browser.close(); await catalogFile.restore() }
